pub(super) fn inspect_artifact_bytes(
    engine: &Engine,
    request: &ArtifactBytesInspectionRequestV1,
) -> Result<ArtifactV1, EngineError> {
    let ready = engine.open_ready_store()?;
    ready.revalidate()?;
    let directories = PreparedDirectories::open(&ready, false)?.ok_or_else(|| {
        prepared_error(engine.config.state_root(), PreparedStoreIssue::MissingPlan)
    })?;
    let record = load_record_from(&ready, &directories, request.plan_id())?;
    let artifact = find_artifact(engine, &record, request.artifact_id())?;
    if artifact.byte_len() > request.max_artifact_bytes() {
        return Err(prepared_error(
            engine.config.state_root(),
            PreparedStoreIssue::EntryTooLarge {
                limit: request.max_artifact_bytes(),
                actual: artifact.byte_len(),
            },
        ));
    }
    let bytes = read_blob_with_limit(
        &ready,
        &directories,
        artifact.digest(),
        request.max_artifact_bytes(),
    )?;
    if malm_types::usize_to_u64(bytes.len()) != artifact.byte_len() {
        return Err(prepared_error(
            &blob_path(engine.config.state_root(), artifact.digest()),
            PreparedStoreIssue::ObservationChanged,
        ));
    }
    Ok(ArtifactV1::new(artifact_descriptor(artifact), bytes))
}

