fn append_mandatory_findings(
    engine: &Engine,
    findings: &mut Vec<PolicyFindingV1>,
    operations: &[PreparedOperationV1],
    previous: Option<&StateGenerationV1>,
    drifted: &DriftedTargets,
    restored: &RestoredTargets,
    synthesized: &BTreeSet<(DeploymentName, String)>,
) -> Result<(), EngineError> {
    let mut finding_ids = findings
        .iter()
        .map(|finding| finding.id().clone())
        .collect::<BTreeSet<_>>();
    // Restoring absent leaves destroys nothing, so findings stay advisory.
    // Created ancestors become owned by this namespace.
    for operation in operations {
        let observation = operation.observation();
        if matches!(observation.leaf(), LeafObservationV1::Present(_)) {
            continue;
        }
        let key = (
            observation.authority().clone(),
            observation.relative_path().to_owned(),
        );
        let (code, action) = if restored.contains(&key) {
            (
                "restore-missing",
                "restore externally deleted managed target",
            )
        } else if matches!(operation, PreparedOperationV1::EnsureDirectory { .. })
            && synthesized.contains(&key)
        {
            (
                "restore-missing-directory",
                "create missing managed ancestor directory",
            )
        } else {
            continue;
        };
        let finding = PolicyFindingV1::new(
            code,
            format!(
                "{action} {}:{}",
                observation.authority(),
                observation.relative_path()
            ),
            false,
        )
        .map_err(|error| invalid_record(engine, error))?;
        if finding_ids.insert(finding.id().clone()) {
            findings.push(finding);
        }
    }
    for operation in operations {
        if !matches!(
            operation.observation().leaf(),
            LeafObservationV1::Present(_)
        ) {
            continue;
        }
        // Changes to owned targets are advisory because retained generations
        // remain recoverable. Adopting an unowned target requires approval.
        let owned = previously_owned_target(previous, operation);
        let locally_modified = {
            let observation = operation.observation();
            drifted.contains(&(
                observation.authority().clone(),
                observation.relative_path().to_owned(),
            ))
        };
        let (code, action) = match operation {
            PreparedOperationV1::PlaceFile {
                replace_existing: true,
                ..
            }
            | PreparedOperationV1::PlaceSymlink {
                replace_existing: true,
                ..
            }
            | PreparedOperationV1::PlaceTree {
                replace_existing: true,
                ..
            } => ("replace-existing", "replace existing target"),
            PreparedOperationV1::RemoveLeaf { .. } => ("remove-existing", "remove existing target"),
            PreparedOperationV1::EnsureDirectory { observation, .. }
                if matches!(observation.leaf(), LeafObservationV1::Present(_)) =>
            {
                ("replace-existing", "replace existing target")
            }
            PreparedOperationV1::EnsureDirectory { .. }
            | PreparedOperationV1::PlaceFile {
                replace_existing: false,
                ..
            }
            | PreparedOperationV1::PlaceSymlink {
                replace_existing: false,
                ..
            }
            | PreparedOperationV1::PlaceTree {
                replace_existing: false,
                ..
            }
            | PreparedOperationV1::AssertAbsent { .. }
            | PreparedOperationV1::AssertExact { .. } => continue,
        };
        let observation = operation.observation();
        // Discarding content malm did not write always requires approval.
        let (code, action) = if locally_modified {
            (
                "restore-modified",
                "discard local modifications and restore",
            )
        } else {
            (code, action)
        };
        let finding = PolicyFindingV1::new(
            code,
            format!(
                "{action} {}:{}",
                observation.authority(),
                observation.relative_path()
            ),
            !owned || locally_modified,
        )
        .map_err(|error| invalid_record(engine, error))?;
        if finding_ids.insert(finding.id().clone()) {
            findings.push(finding);
        }
    }
    Ok(())
}

fn previously_owned_target(
    previous: Option<&StateGenerationV1>,
    operation: &PreparedOperationV1,
) -> bool {
    let Some(generation) = previous else {
        return false;
    };
    if !generation.lifecycle_state().is_enabled() {
        return false;
    }
    let observation = operation.observation();
    generation
        .desired_snapshot()
        .targets()
        .binary_search_by(|target| {
            (target.authority(), target.relative_path())
                .cmp(&(observation.authority(), observation.relative_path()))
        })
        .is_ok_and(|index| generation.desired_snapshot().targets()[index].is_present())
}

fn observe_operation(
    engine: &Engine,
    ready: &ReadyStoreRoot<'_>,
    operation: &PrepareOperationV1,
    previous: Option<&StateGenerationV1>,
) -> Result<PreparedOperationV1, EngineError> {
    let observation = observe_target(engine, ready, operation, previous)?;
    Ok(match operation {
        PrepareOperationV1::EnsureDirectory { mode, .. }
            if !previous_owns_target(previous, operation)
                && matches!(
                observation.leaf(),
                LeafObservationV1::Present(identity)
                    if FileType::from_raw_mode(identity.mode) == FileType::Directory
                        && identity.mode & 0o7777 == *mode
                ) =>
        {
            PreparedOperationV1::AssertExact {
                observation,
                state: StateTargetStateV1::Directory {
                    directory: Some(
                        StateDirectoryV1::new(*mode)
                            .map_err(|error| invalid_record(engine, error))?,
                    ),
                },
            }
        }
        PrepareOperationV1::EnsureDirectory { mode, .. } => PreparedOperationV1::EnsureDirectory {
            observation,
            mode: *mode,
        },
        PrepareOperationV1::PlaceFile {
            artifact_id, mode, ..
        } => PreparedOperationV1::PlaceFile {
            replace_existing: matches!(observation.leaf(), LeafObservationV1::Present(_)),
            observation,
            artifact_id: artifact_id.clone(),
            mode: *mode,
        },
        PrepareOperationV1::PlaceSymlink { object, .. } => PreparedOperationV1::PlaceSymlink {
            replace_existing: matches!(observation.leaf(), LeafObservationV1::Present(_)),
            observation,
            object: object.clone(),
        },
        PrepareOperationV1::PlaceTree {
            tree,
            archive_provenance,
            ..
        } => PreparedOperationV1::PlaceTree {
            replace_existing: matches!(observation.leaf(), LeafObservationV1::Present(_)),
            observation,
            tree: tree.clone(),
            archive_provenance: archive_provenance
                .as_ref()
                .map(|provenance| archive_provenance_record(engine, provenance))
                .transpose()?,
        },
        PrepareOperationV1::RemoveLeaf { .. } => PreparedOperationV1::RemoveLeaf { observation },
        PrepareOperationV1::AssertAbsent { .. } => {
            PreparedOperationV1::AssertAbsent { observation }
        }
        PrepareOperationV1::AssertExact { state, .. } => PreparedOperationV1::AssertExact {
            observation,
            state: target_state_record(engine, state)?,
        },
    })
}

fn observe_target(
    engine: &Engine,
    ready: &ReadyStoreRoot<'_>,
    operation: &PrepareOperationV1,
    previous: Option<&StateGenerationV1>,
) -> Result<TargetObservationV1, EngineError> {
    let authority = operation.authority();
    let target_root = engine.config.target_root(authority).ok_or_else(|| {
        prepared_error(
            engine.config.state_root(),
            PreparedStoreIssue::UnknownTargetAuthority(authority.clone()),
        )
    })?;
    let absolute = target_root.join(operation.relative_path());
    if super::paths_overlap(&absolute, engine.config.state_root()) {
        return Err(unsafe_target(
            &absolute,
            "destination enters protected state",
        ));
    }

    let chain = PinnedDirectoryChain::open(target_root)
        .map_err(|source| errno_error("open managed target authority", target_root, source))?;
    let root = chain.directory();
    let root_stat = fstat(root)
        .map_err(|source| errno_error("inspect managed target authority", target_root, source))?;
    validate_target_directory(engine, target_root, &root_stat)?;
    reject_state_traversal_directory(ready, root, target_root, &absolute)?;

    let segments = operation.relative_path().split('/').collect::<Vec<_>>();
    let parent_segments = &segments[..segments.len() - 1];
    let mut current = root.try_clone().map_err(|source| EngineError::Io {
        operation: "clone managed target root",
        path: target_root.to_path_buf(),
        source,
    })?;
    let mut ancestors = Vec::new();
    // Earlier directory operations must recreate any missing parent suffix.
    let mut missing_ancestors = 0_u32;
    for (index, segment) in parent_segments.iter().enumerate() {
        let path = target_root.join(segments[..=index].join("/"));
        let next = match openat2(
            &current,
            *segment,
            DIRECTORY_FLAGS | OFlags::NOFOLLOW | OFlags::NOATIME,
            Mode::empty(),
            ROOT_RESOLVE_FLAGS,
        ) {
            Ok(next) => File::from(next),
            Err(rustix::io::Errno::NOENT) => {
                missing_ancestors = u32::try_from(parent_segments.len() - index)
                    .expect("validated relative path depth fits in u32");
                // The deepest existing directory becomes the observation parent.
                ancestors.pop();
                break;
            }
            Err(source) => {
                return Err(errno_error("open managed target ancestor", &path, source));
            }
        };
        let stat = fstat(&next)
            .map_err(|source| errno_error("inspect managed target ancestor", &path, source))?;
        validate_target_directory(engine, &path, &stat)?;
        reject_state_traversal_directory(ready, &next, &path, &absolute)?;
        if index + 1 < parent_segments.len() {
            ancestors.push(file_identity(&stat));
        }
        current = next;
    }
    let parent_stat = fstat(&current)
        .map_err(|source| errno_error("inspect managed target parent", &absolute, source))?;
    let leaf_name = segments.last().expect("validated relative path has a leaf");
    let leaf_stat = if missing_ancestors > 0 {
        // A leaf below a missing directory is absent and cannot be inspected.
        None
    } else {
        match statat(&current, *leaf_name, AtFlags::SYMLINK_NOFOLLOW) {
            Ok(stat) => Some(stat),
            Err(rustix::io::Errno::NOENT) => None,
            Err(source) => {
                return Err(errno_error(
                    "inspect managed target leaf",
                    &absolute,
                    source,
                ));
            }
        }
    };
    validate_leaf_for_operation(
        engine,
        operation,
        leaf_stat.as_ref(),
        previous_owns_target(previous, operation),
        &absolute,
    )?;
    let destructive_directory_change =
        matches!(operation, PrepareOperationV1::RemoveLeaf { .. }) || operation.replaces_existing();
    let prior_is_managed_tree = previous_target_state(previous, operation)
        .is_some_and(|state| matches!(state, StateTargetStateV1::Tree { tree: Some(_) }));
    if leaf_stat
        .as_ref()
        .is_some_and(|stat| FileType::from_raw_mode(stat.st_mode) == FileType::Directory)
    {
        let flags = if destructive_directory_change {
            DIRECTORY_FLAGS | OFlags::NOFOLLOW | OFlags::NOATIME
        } else {
            ROOT_DIRECTORY_FLAGS
        };
        let leaf = openat2(&current, *leaf_name, flags, Mode::empty(), RESOLVE_FLAGS)
            .map(File::from)
            .map_err(|source| {
                errno_error("open managed target directory leaf", &absolute, source)
            })?;
        reject_state_destination_directory(ready, &leaf, &absolute, &absolute)?;
        if destructive_directory_change && !prior_is_managed_tree {
            require_empty_target_directory(&leaf, &absolute)?;
        }
        let after = fstat(&leaf).map_err(|source| {
            errno_error("reinspect managed target directory leaf", &absolute, source)
        })?;
        let rebound = match statat(&current, *leaf_name, AtFlags::SYMLINK_NOFOLLOW) {
            Ok(stat) => stat,
            Err(rustix::io::Errno::NOENT | rustix::io::Errno::NOTDIR) => {
                return Err(prepared_error(
                    &absolute,
                    PreparedStoreIssue::ObservationChanged,
                ));
            }
            Err(source) => {
                return Err(errno_error(
                    "revalidate managed target directory leaf",
                    &absolute,
                    source,
                ));
            }
        };
        if !same_file_snapshot(leaf_stat.as_ref().expect("directory was observed"), &after)
            || !same_file_snapshot(&after, &rebound)
        {
            return Err(prepared_error(
                &absolute,
                PreparedStoreIssue::ObservationChanged,
            ));
        }
    }
    chain.ensure_bound(target_root)?;
    ready.revalidate()?;

    TargetObservationV1::with_missing_ancestors(
        authority.clone(),
        operation.relative_path(),
        file_identity(&root_stat),
        ancestors,
        file_identity(&parent_stat),
        leaf_stat
            .as_ref()
            .map_or(LeafObservationV1::Absent, |stat| {
                LeafObservationV1::Present(file_identity(stat))
            }),
        missing_ancestors,
    )
    .map_err(|error| invalid_record(engine, error))
}

fn validate_target_directory(engine: &Engine, path: &Path, stat: &Stat) -> Result<(), EngineError> {
    if FileType::from_raw_mode(stat.st_mode) != FileType::Directory {
        return Err(unsafe_target(path, "path component is not a directory"));
    }
    if stat.st_uid != engine.effective_user_id() {
        return Err(unsafe_target(path, "directory is owned by another user"));
    }
    if stat.st_mode & 0o7022 != 0 {
        return Err(unsafe_target(
            path,
            "directory is group/other writable or has special mode bits",
        ));
    }
    Ok(())
}

fn validate_leaf_for_operation(
    engine: &Engine,
    operation: &PrepareOperationV1,
    leaf: Option<&Stat>,
    previously_owned: bool,
    path: &Path,
) -> Result<(), EngineError> {
    let file_type = leaf.map(|stat| FileType::from_raw_mode(stat.st_mode));
    if let Some(stat) = leaf
        && stat.st_uid != engine.effective_user_id()
    {
        return Err(unsafe_target(path, "target leaf is owned by another user"));
    }
    match operation {
        PrepareOperationV1::PlaceFile {
            replace_existing: false,
            ..
        }
        | PrepareOperationV1::PlaceSymlink {
            replace_existing: false,
            ..
        }
        | PrepareOperationV1::PlaceTree {
            replace_existing: false,
            ..
        } if leaf.is_some() && !previously_owned => {
            return Err(unsafe_target(
                path,
                "placement conflict policy requires the leaf to be absent",
            ));
        }
        PrepareOperationV1::AssertAbsent { .. } if leaf.is_some() => {
            return Err(unsafe_target(path, "assert-absent requires an absent leaf"));
        }
        PrepareOperationV1::AssertExact { .. } if leaf.is_none() => {
            return Err(unsafe_target(path, "assert-exact requires a present leaf"));
        }
        _ => {}
    }
    if let Some(stat) = leaf
        && file_type != Some(FileType::Directory)
        && stat.st_nlink != 1
    {
        return Err(unsafe_target(
            path,
            "non-directory leaf has multiple hard links",
        ));
    }
    Ok(())
}

fn previous_owns_target(
    previous: Option<&StateGenerationV1>,
    operation: &PrepareOperationV1,
) -> bool {
    previous.is_some_and(|generation| {
        generation.lifecycle_state().is_enabled()
            && generation
                .desired_snapshot()
                .targets()
                .iter()
                .any(|target| {
                    target.is_present()
                        && target.authority() == operation.authority()
                        && target.relative_path() == operation.relative_path()
                })
    })
}

fn previous_target_state<'a>(
    previous: Option<&'a StateGenerationV1>,
    operation: &PrepareOperationV1,
) -> Option<&'a StateTargetStateV1> {
    previous
        .filter(|generation| generation.lifecycle_state().is_enabled())?
        .desired_snapshot()
        .targets()
        .iter()
        .find(|target| {
            target.authority() == operation.authority()
                && target.relative_path() == operation.relative_path()
        })
        .map(StateTargetV1::state)
}

fn require_empty_target_directory(directory: &File, path: &Path) -> Result<(), EngineError> {
    const NAMED_ENTRIES: usize = 3;
    let mut entries = Dir::read_from(directory)
        .map_err(|source| errno_error("enumerate managed target directory", path, source))?;
    let mut named = Vec::new();
    let mut more = 0_usize;
    while let Some(entry) = entries.read() {
        let entry = entry
            .map_err(|source| errno_error("enumerate managed target directory", path, source))?;
        if matches!(entry.file_name().to_bytes(), b"." | b"..") {
            continue;
        }
        if named.len() < NAMED_ENTRIES {
            named.push(format!(
                "\"{}\"",
                entry.file_name().to_string_lossy().escape_default()
            ));
        } else {
            more += 1;
        }
    }
    if named.is_empty() {
        return Ok(());
    }
    named.sort_unstable();
    let mut listed = named.join(", ");
    if more > 0 {
        listed.push_str(&format!(" and {more} more"));
    }
    Err(unsafe_target(
        path,
        &format!(
            "directory is not empty and is not managed by malm (contains {listed}); \
             move it away first (for example: mv -- {path} {path}.backup) or delete it, \
             then re-run",
            path = path.display()
        ),
    ))
}

fn reject_state_traversal_directory(
    ready: &ReadyStoreRoot<'_>,
    directory: &File,
    directory_path: &Path,
    target_path: &Path,
) -> Result<(), EngineError> {
    let overlaps = directory_contains(&ready.state, directory, ready.config.state_parent())?
        || directory_is_mount_alias_of(
            &ready.state,
            ready.config.state_root(),
            directory,
            directory_path,
        )?;
    if overlaps {
        return Err(unsafe_target(
            target_path,
            "destination is physically inside protected state",
        ));
    }
    Ok(())
}

fn reject_state_destination_directory(
    ready: &ReadyStoreRoot<'_>,
    directory: &File,
    directory_path: &Path,
    target_path: &Path,
) -> Result<(), EngineError> {
    reject_state_traversal_directory(ready, directory, directory_path, target_path)?;
    let contains_state = directory_contains(directory, &ready.state, ready.config.state_parent())?
        || directory_is_mount_alias_of(
            directory,
            directory_path,
            &ready.state,
            ready.config.state_root(),
        )?;
    if contains_state {
        return Err(unsafe_target(
            target_path,
            "destination is physically inside protected state",
        ));
    }
    Ok(())
}

fn file_identity(stat: &Stat) -> FileIdentityV1 {
    FileIdentityV1 {
        device: stat.st_dev,
        inode: stat.st_ino,
        user_id: stat.st_uid,
        group_id: stat.st_gid,
        mode: stat.st_mode,
        links: stat.st_nlink,
        size: u64::try_from(stat.st_size).unwrap_or(u64::MAX),
        modified_seconds: stat.st_mtime,
        modified_nanoseconds: u32::try_from(stat.st_mtime_nsec).unwrap_or(u32::MAX),
        changed_seconds: stat.st_ctime,
        changed_nanoseconds: u32::try_from(stat.st_ctime_nsec).unwrap_or(u32::MAX),
    }
}

pub(super) struct PreparedDirectories {
    objects: File,
    blobs: File,
    prepared: File,
    objects_path: PathBuf,
    blobs_path: PathBuf,
    prepared_path: PathBuf,
}

impl PreparedDirectories {
    pub(super) fn open(
        ready: &ReadyStoreRoot<'_>,
        create: bool,
    ) -> Result<Option<Self>, EngineError> {
        let objects_path = ready.config.state_root().join(OBJECTS_DIR);
        let Some(objects) = open_container(
            &ready.state_io,
            OBJECTS_DIR,
            &objects_path,
            create,
            ready.expected_user_id,
        )?
        else {
            return Ok(None);
        };
        let blobs_path = objects_path.join(BLOBS_DIR);
        let Some(blobs) = open_container(
            &objects,
            BLOBS_DIR,
            &blobs_path,
            create,
            ready.expected_user_id,
        )?
        else {
            return Ok(None);
        };
        let prepared_path = ready.config.state_root().join(PREPARED_DIR);
        let Some(prepared) = open_container(
            &ready.state_io,
            PREPARED_DIR,
            &prepared_path,
            create,
            ready.expected_user_id,
        )?
        else {
            return Ok(None);
        };
        let result = Self {
            objects,
            blobs,
            prepared,
            objects_path,
            blobs_path,
            prepared_path,
        };
        result.revalidate(ready)?;
        Ok(Some(result))
    }

    fn revalidate(&self, ready: &ReadyStoreRoot<'_>) -> Result<(), EngineError> {
        ensure_container_bound(
            &ready.state_io,
            OBJECTS_DIR,
            &self.objects,
            &self.objects_path,
            ready.expected_user_id,
        )?;
        ensure_container_bound(
            &self.objects,
            BLOBS_DIR,
            &self.blobs,
            &self.blobs_path,
            ready.expected_user_id,
        )?;
        ensure_container_bound(
            &ready.state_io,
            PREPARED_DIR,
            &self.prepared,
            &self.prepared_path,
            ready.expected_user_id,
        )?;
        ready.revalidate()
    }
}

fn open_container(
    parent: &File,
    leaf: &str,
    path: &Path,
    create: bool,
    expected_uid: u32,
) -> Result<Option<File>, EngineError> {
    let observed = match statat(parent, leaf, AtFlags::SYMLINK_NOFOLLOW) {
        Ok(stat) => stat,
        Err(rustix::io::Errno::NOENT) if !create => return Ok(None),
        Err(rustix::io::Errno::NOENT) => {
            match mkdirat(parent, leaf, Mode::from_raw_mode(CONTAINER_MODE)) {
                Ok(()) => {}
                Err(rustix::io::Errno::EXIST) => {}
                Err(source) => {
                    return Err(errno_error("create prepared-store container", path, source));
                }
            }
            statat(parent, leaf, AtFlags::SYMLINK_NOFOLLOW)
                .map_err(|source| errno_error("inspect prepared-store container", path, source))?
        }
        Err(source) => {
            return Err(errno_error(
                "inspect prepared-store container",
                path,
                source,
            ));
        }
    };
    validate_container(path, &observed, expected_uid)?;
    let directory = openat2(
        parent,
        leaf,
        DIRECTORY_FLAGS | OFlags::NOFOLLOW | OFlags::NOATIME,
        Mode::empty(),
        ROOT_RESOLVE_FLAGS,
    )
    .map(File::from)
    .map_err(|source| errno_error("open prepared-store container", path, source))?;
    let opened = fstat(&directory)
        .map_err(|source| errno_error("inspect opened prepared-store container", path, source))?;
    validate_container(path, &opened, expected_uid)?;
    if !same_object(&observed, &opened) {
        return Err(prepared_error(path, PreparedStoreIssue::ObservationChanged));
    }
    if create {
        fsync(&directory)
            .map_err(|source| errno_error("sync prepared-store container", path, source))?;
        fsync(parent)
            .map_err(|source| errno_error("sync prepared-store container parent", path, source))?;
    }
    Ok(Some(directory))
}

fn validate_container(path: &Path, stat: &Stat, expected_uid: u32) -> Result<(), EngineError> {
    if FileType::from_raw_mode(stat.st_mode) != FileType::Directory {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::ContainerNotDirectory,
        ));
    }
    validate_owner_mode(path, stat, expected_uid, CONTAINER_MODE, None)
}

fn ensure_container_bound(
    parent: &File,
    leaf: &str,
    directory: &File,
    path: &Path,
    expected_uid: u32,
) -> Result<(), EngineError> {
    let pinned = fstat(directory)
        .map_err(|source| errno_error("inspect pinned prepared-store container", path, source))?;
    validate_container(path, &pinned, expected_uid)?;
    let bound = statat(parent, leaf, AtFlags::SYMLINK_NOFOLLOW)
        .map_err(|source| errno_error("revalidate prepared-store container", path, source))?;
    validate_container(path, &bound, expected_uid)?;
    if !same_object(&pinned, &bound) {
        return Err(prepared_error(path, PreparedStoreIssue::ObservationChanged));
    }
    Ok(())
}

pub(super) fn publish_blob(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    digest: &Digest,
    bytes: &[u8],
) -> Result<(), EngineError> {
    if malm_types::usize_to_u64(bytes.len()) > malm_store::MAX_ARTIFACT_BLOB_BYTES {
        return Err(prepared_error(
            &blob_path(ready.config.state_root(), digest),
            PreparedStoreIssue::EntryTooLarge {
                limit: malm_store::MAX_ARTIFACT_BLOB_BYTES,
                actual: malm_types::usize_to_u64(bytes.len()),
            },
        ));
    }
    if &Digest::sha256(bytes) != digest {
        return Err(prepared_error(
            &blob_path(ready.config.state_root(), digest),
            PreparedStoreIssue::DigestMismatch {
                expected: digest.clone(),
                actual: Digest::sha256(bytes),
            },
        ));
    }
    let path = blob_path(ready.config.state_root(), digest);
    // Cache hits validate the content-addressed name and length. Publication
    // proved the bytes, and every read verifies the digest again.
    match statat(
        &directories.blobs,
        digest.as_str(),
        AtFlags::SYMLINK_NOFOLLOW,
    ) {
        Ok(stat) => {
            if FileType::from_raw_mode(stat.st_mode) == FileType::RegularFile
                && stat.st_uid == ready.expected_user_id
                && u64::try_from(stat.st_size).ok() == Some(malm_types::usize_to_u64(bytes.len()))
            {
                engine_failpoint!("v1.prepare.blob.after_publish");
                return Ok(());
            }
        }
        Err(rustix::io::Errno::NOENT) => {}
        Err(source) => {
            return Err(errno_error("inspect prepared-store blob", &path, source));
        }
    }
    publish_bytes(
        ready,
        directories,
        &directories.blobs,
        digest.as_str(),
        &path,
        bytes,
        PublishedEntryKind::ArtifactBlob,
    )?;
    engine_failpoint!("v1.prepare.blob.after_publish");
    Ok(())
}

/// Stat-proves a retained blob by content-addressed name and exact length.
/// Publication and every later read verify its digest.
fn require_retained_blob(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    digest: &Digest,
    byte_len: u64,
) -> Result<(), EngineError> {
    let path = blob_path(ready.config.state_root(), digest);
    let stat = statat(
        &directories.blobs,
        digest.as_str(),
        AtFlags::SYMLINK_NOFOLLOW,
    )
    .map_err(|_| prepared_error(&path, PreparedStoreIssue::MissingBlob))?;
    if FileType::from_raw_mode(stat.st_mode) != FileType::RegularFile
        || stat.st_uid != ready.expected_user_id
        || u64::try_from(stat.st_size).ok() != Some(byte_len)
    {
        return Err(prepared_error(
            &path,
            PreparedStoreIssue::ObservationChanged,
        ));
    }
    Ok(())
}

fn publish_record(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    plan_id: &PreparedId,
    encoded_record: &[u8],
) -> Result<(), EngineError> {
    publish_bytes(
        ready,
        directories,
        &directories.prepared,
        plan_id.as_str(),
        &record_path(ready.config.state_root(), plan_id),
        encoded_record,
        PublishedEntryKind::PreparedRecord,
    )?;
    Ok(())
}

fn publish_bytes(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    parent: &File,
    leaf: &str,
    path: &Path,
    bytes: &[u8],
    kind: PublishedEntryKind,
) -> Result<(), EngineError> {
    if statat(parent, leaf, AtFlags::SYMLINK_NOFOLLOW).is_ok() {
        return verify_and_sync_existing_entry(ready, directories, parent, leaf, path, bytes);
    }
    let mut temporary = openat2(
        parent,
        ".",
        OFlags::TMPFILE | OFlags::RDWR | OFlags::CLOEXEC,
        Mode::from_raw_mode(ENTRY_MODE),
        ROOT_RESOLVE_FLAGS,
    )
    .map(File::from)
    .map_err(|source| errno_error("create unnamed prepared-store entry", path, source))?;
    fchmod(&temporary, Mode::from_raw_mode(ENTRY_MODE))
        .map_err(|source| errno_error("set prepared-store entry mode", path, source))?;
    temporary
        .write_all(bytes)
        .map_err(|source| EngineError::Io {
            operation: "write prepared-store entry",
            path: path.to_path_buf(),
            source,
        })?;
    temporary.flush().map_err(|source| EngineError::Io {
        operation: "flush prepared-store entry",
        path: path.to_path_buf(),
        source,
    })?;
    fsync(&temporary).map_err(|source| errno_error("sync prepared-store entry", path, source))?;
    directories.revalidate(ready)?;
    match linkat(&temporary, "", parent, leaf, AtFlags::EMPTY_PATH) {
        Ok(()) => {
            if kind == PublishedEntryKind::PreparedRecord {
                engine_failpoint!("v1.prepare.record.after_link");
            }
        }
        Err(rustix::io::Errno::EXIST) => {
            verify_and_sync_existing_entry(ready, directories, parent, leaf, path, bytes)?;
        }
        Err(source) => return Err(errno_error("publish prepared-store entry", path, source)),
    }
    fsync(parent).map_err(|source| errno_error("sync prepared-store directory", path, source))?;
    directories.revalidate(ready)
}

fn verify_and_sync_existing_entry(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    parent: &File,
    leaf: &str,
    path: &Path,
    expected: &[u8],
) -> Result<(), EngineError> {
    let actual = read_entry(
        ready,
        directories,
        parent,
        leaf,
        path,
        u64::try_from(expected.len()).unwrap_or(u64::MAX),
        PreparedStoreIssue::ObservationChanged,
    )?;
    if actual != expected {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::DigestMismatch {
                expected: Digest::sha256(expected),
                actual: Digest::sha256(actual),
            },
        ));
    }
    let file = openat2(
        parent,
        leaf,
        OFlags::RDONLY | OFlags::NONBLOCK | OFlags::NOFOLLOW | OFlags::CLOEXEC,
        Mode::empty(),
        ROOT_RESOLVE_FLAGS,
    )
    .map(File::from)
    .map_err(|source| errno_error("open existing prepared-store entry", path, source))?;
    fsync(&file)
        .map_err(|source| errno_error("sync existing prepared-store entry", path, source))?;
    fsync(parent).map_err(|source| errno_error("sync prepared-store directory", path, source))?;
    directories.revalidate(ready)
}

fn load_record_from(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    plan_id: &PreparedId,
) -> Result<PreparedRecordV1, EngineError> {
    load_record_from_with_limit(
        ready,
        directories,
        plan_id,
        malm_store::MAX_PREPARED_RECORD_BYTES as u64,
    )
    .map(|(record, _)| record)
}

fn load_record_from_with_limit(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    plan_id: &PreparedId,
    max_decoded_bytes: u64,
) -> Result<(PreparedRecordV1, u64), EngineError> {
    let path = record_path(ready.config.state_root(), plan_id);
    let maximum = max_decoded_bytes.min(malm_store::MAX_PREPARED_RECORD_BYTES as u64);
    let bytes = read_entry(
        ready,
        directories,
        &directories.prepared,
        plan_id.as_str(),
        &path,
        maximum,
        PreparedStoreIssue::MissingPlan,
    )?;
    let decoded_bytes = malm_types::usize_to_u64(bytes.len());
    let record = decode_prepared_record_v1(plan_id, &bytes).map_err(|error| {
        prepared_error(
            &path,
            PreparedStoreIssue::InvalidRecord {
                detail: error.to_string(),
            },
        )
    })?;
    Ok((record, decoded_bytes))
}

fn read_blob(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    digest: &Digest,
) -> Result<Vec<u8>, EngineError> {
    read_blob_with_limit(
        ready,
        directories,
        digest,
        malm_store::MAX_ARTIFACT_BLOB_BYTES,
    )
}

fn read_blob_with_limit(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    digest: &Digest,
    max_bytes: u64,
) -> Result<Vec<u8>, EngineError> {
    let path = blob_path(ready.config.state_root(), digest);
    let bytes = read_entry(
        ready,
        directories,
        &directories.blobs,
        digest.as_str(),
        &path,
        max_bytes,
        PreparedStoreIssue::MissingBlob,
    )?;
    let actual = Digest::sha256(&bytes);
    if &actual != digest {
        return Err(prepared_error(
            &path,
            PreparedStoreIssue::DigestMismatch {
                expected: digest.clone(),
                actual,
            },
        ));
    }
    Ok(bytes)
}

fn read_entry(
    ready: &ReadyStoreRoot<'_>,
    directories: &PreparedDirectories,
    parent: &File,
    leaf: &str,
    path: &Path,
    max_bytes: u64,
    missing: PreparedStoreIssue,
) -> Result<Vec<u8>, EngineError> {
    let observed = match statat(parent, leaf, AtFlags::SYMLINK_NOFOLLOW) {
        Ok(stat) => stat,
        Err(rustix::io::Errno::NOENT) => return Err(prepared_error(path, missing)),
        Err(source) => return Err(errno_error("inspect prepared-store entry", path, source)),
    };
    validate_entry(path, &observed, ready.expected_user_id, max_bytes)?;
    let mut file = openat2(
        parent,
        leaf,
        OFlags::RDONLY | OFlags::NONBLOCK | OFlags::NOFOLLOW | OFlags::NOATIME | OFlags::CLOEXEC,
        Mode::empty(),
        ROOT_RESOLVE_FLAGS,
    )
    .map(File::from)
    .map_err(|source| errno_error("open prepared-store entry", path, source))?;
    let opened = fstat(&file)
        .map_err(|source| errno_error("inspect opened prepared-store entry", path, source))?;
    validate_entry(path, &opened, ready.expected_user_id, max_bytes)?;
    if !same_file_snapshot(&observed, &opened) {
        return Err(prepared_error(path, PreparedStoreIssue::ObservationChanged));
    }
    let initial_capacity = u64::try_from(opened.st_size).unwrap_or(0).min(max_bytes);
    let mut bytes = Vec::with_capacity(usize::try_from(initial_capacity).unwrap_or(0));
    (&mut file)
        .take(max_bytes.saturating_add(1))
        .read_to_end(&mut bytes)
        .map_err(|source| EngineError::Io {
            operation: "read prepared-store entry",
            path: path.to_path_buf(),
            source,
        })?;
    let actual_size = u64::try_from(bytes.len()).unwrap_or(u64::MAX);
    if actual_size > max_bytes {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::EntryTooLarge {
                limit: max_bytes,
                actual: actual_size,
            },
        ));
    }
    let after = fstat(&file)
        .map_err(|source| errno_error("reinspect prepared-store entry", path, source))?;
    if !same_file_snapshot(&opened, &after) {
        return Err(prepared_error(path, PreparedStoreIssue::ObservationChanged));
    }
    directories.revalidate(ready)?;
    Ok(bytes)
}

fn validate_entry(
    path: &Path,
    stat: &Stat,
    expected_uid: u32,
    max_bytes: u64,
) -> Result<(), EngineError> {
    if FileType::from_raw_mode(stat.st_mode) != FileType::RegularFile {
        return Err(prepared_error(path, PreparedStoreIssue::EntryNotRegular));
    }
    validate_owner_mode(path, stat, expected_uid, ENTRY_MODE, Some(1))?;
    let actual_size = u64::try_from(stat.st_size).unwrap_or(u64::MAX);
    if actual_size > max_bytes {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::EntryTooLarge {
                limit: max_bytes,
                actual: actual_size,
            },
        ));
    }
    Ok(())
}

fn validate_owner_mode(
    path: &Path,
    stat: &Stat,
    expected_uid: u32,
    expected_mode: u32,
    expected_links: Option<u64>,
) -> Result<(), EngineError> {
    if stat.st_uid != expected_uid {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::WrongOwner {
                expected_uid,
                actual_uid: stat.st_uid,
            },
        ));
    }
    let mode = stat.st_mode & 0o7777;
    if mode != expected_mode {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::UnexpectedMode {
                expected: expected_mode,
                actual: mode,
            },
        ));
    }
    if let Some(expected) = expected_links
        && stat.st_nlink != expected
    {
        return Err(prepared_error(
            path,
            PreparedStoreIssue::UnexpectedLinks {
                expected,
                actual: stat.st_nlink,
            },
        ));
    }
    Ok(())
}

fn project(
    plan_id: &PreparedId,
    record: &PreparedRecordV1,
) -> Result<PreparedDeploymentV1, EngineError> {
    Ok(PreparedDeploymentV1::from(PreparedDeploymentPartsV1 {
        plan_id: plan_id.clone(),
        namespace: record.namespace().clone(),
        expected_head: record.expected_head().cloned(),
        graph_digest: record.graph_digest().clone(),
        inputs: record
            .inputs()
            .iter()
            .map(|input| input_view(plan_id, input))
            .collect::<Result<Vec<_>, _>>()?,
        transforms: record
            .transforms()
            .iter()
            .map(|transform| transform_view(plan_id, transform))
            .collect::<Result<Vec<_>, _>>()?,
        artifacts: record.artifacts().iter().map(artifact_descriptor).collect(),
        findings: record
            .findings()
            .iter()
            .map(|finding| {
                PolicyFindingViewV1::new(
                    finding.id().clone(),
                    finding.code().to_owned(),
                    finding.message().to_owned(),
                    finding.approval_required(),
                )
            })
            .collect(),
        approval_digest: record.approval_digest().clone(),
        operations: record
            .operations()
            .iter()
            .map(operation_view)
            .collect::<Result<Vec<_>, _>>()?,
    })
    .with_transition(match record.transition() {
        PreparedTransitionV1::Reconcile => LifecycleTransitionViewV1::Reconcile,
        PreparedTransitionV1::Disable => LifecycleTransitionViewV1::Disable,
        PreparedTransitionV1::Enable { restore_point } => LifecycleTransitionViewV1::Enable {
            restore_generation: restore_point.generation().clone(),
        },
        PreparedTransitionV1::Checkout { source_generation } => {
            LifecycleTransitionViewV1::Checkout {
                source_generation: source_generation.clone(),
            }
        }
        PreparedTransitionV1::RetentionAuthority => LifecycleTransitionViewV1::RetentionAuthority,
        PreparedTransitionV1::NamespaceRemoval { .. } => {
            LifecycleTransitionViewV1::NamespaceRemoval {
                drops_history: true,
            }
        }
    })
    .with_lifecycle_state(match record.lifecycle_state() {
        LifecycleStateV1::Enabled => LifecycleStateViewV1::Enabled,
        LifecycleStateV1::Disabled => LifecycleStateViewV1::Disabled,
    })
    .with_restore_point(record.restore_point().map(restore_point_view))
    .with_retention_authority(RetentionAuthorityInspectionV1::new(
        record.retention_authority().history().generations(),
        record
            .retention_authority()
            .restore_points()
            .iter()
            .map(restore_point_view)
            .collect(),
        record.retention_authority().explicit_pins().to_vec(),
    ))
    .with_tracking_review(
        record
            .tracked_root()
            .map(|tracked| prepared_tracking_view(plan_id, tracked))
            .transpose()?,
    ))
}

fn restore_point_view(point: &RestorePointV1) -> RestorePointInspectionV1 {
    RestorePointInspectionV1::new(
        point.generation().clone(),
        match point.lifecycle() {
            LifecycleStateV1::Enabled => LifecycleStateViewV1::Enabled,
            LifecycleStateV1::Disabled => LifecycleStateViewV1::Disabled,
        },
        point.desired_snapshot_digest().clone(),
        point.tracked_root().map(tracked_root_view),
    )
}

fn tracked_root_view(tracked: &TrackedRootV1) -> TrackedRootInspectionV1 {
    TrackedRootInspectionV1::new(
        tracked.moving_selector().as_str().to_owned(),
        tracked.applied_revision().as_str().to_owned(),
        tracked.root_tree_digest().clone(),
    )
}

fn prepared_tracking_view(
    plan_id: &PreparedId,
    tracked: &TrackedRootV1,
) -> Result<PreparedTrackingReviewV1, EngineError> {
    let mut acquisition_grants = Vec::new();
    let mut component_grants = Vec::new();
    let mut target_authority = None;
    for grant in tracked.acquisition_grants() {
        match grant.kind() {
            AcquisitionGrantKindV1::LocalSource => acquisition_grants.push(
                PreparedTrackingAcquisitionGrantV1::new(
                    PreparedTrackingAcquisitionKindV1::LocalSource,
                    grant.locator().as_str(),
                )
                .map_err(|error| invalid_projected_record(plan_id, error))?,
            ),
            AcquisitionGrantKindV1::GitSource => acquisition_grants.push(
                PreparedTrackingAcquisitionGrantV1::new(
                    PreparedTrackingAcquisitionKindV1::GitSource,
                    grant.locator().as_str(),
                )
                .map_err(|error| invalid_projected_record(plan_id, error))?,
            ),
            AcquisitionGrantKindV1::FormatComponent => component_grants.push(
                Digest::new(grant.locator().as_str())
                    .map_err(|error| invalid_projected_record(plan_id, error))?,
            ),
            AcquisitionGrantKindV1::TargetAuthority => {
                let authority = DeploymentName::new(grant.locator().as_str())
                    .map_err(|error| invalid_projected_record(plan_id, error))?;
                if target_authority.replace(authority).is_some() {
                    return Err(invalid_projected_record(
                        plan_id,
                        "tracking contains multiple target-authority grants".to_owned(),
                    ));
                }
            }
        }
    }
    let target_authority = target_authority.ok_or_else(|| {
        invalid_projected_record(
            plan_id,
            "tracking lacks its target-authority grant".to_owned(),
        )
    })?;
    PreparedTrackingReviewV1::try_from(PreparedTrackingReviewPartsV1 {
        source_locator: tracked.source_locator().as_str().to_owned(),
        moving_selector: tracked.moving_selector().as_str().to_owned(),
        applied_revision: tracked.applied_revision().as_str().to_owned(),
        root_tree_digest: tracked.root_tree_digest().clone(),
        source_subdir: tracked.source_subdir().as_str().to_owned(),
        config_entry_point: tracked.config_entry_point().as_str().to_owned(),
        selected_profile: tracked.selected_profile().clone(),
        target_authority,
        acquisition_grants,
        component_grants,
    })
    .map_err(|error| invalid_projected_record(plan_id, error))
}

pub(super) fn input_view(
    plan_id: &PreparedId,
    input: &PreparedInputV1,
) -> Result<PrepareInputViewV1, EngineError> {
    let kind = PrepareInputKindV1::from(input.kind());
    PrepareInputViewV1::new(kind, input.name(), input.digest().clone())
        .map_err(|error| invalid_projected_record(plan_id, error))
}

pub(super) fn transform_view(
    plan_id: &PreparedId,
    transform: &TransformProvenanceV1,
) -> Result<PrepareTransformProvenanceV1, EngineError> {
    let implementation = match transform.implementation() {
        TransformImplementationV1::BuiltIn { implementation } => {
            PrepareTransformImplementationV1::built_in(implementation)
        }
        TransformImplementationV1::Component {
            pack_node_id,
            pack_content_digest,
            component_path,
            component_digest,
            interface_version,
            execution_profile_digest,
        } => PrepareTransformImplementationV1::component(
            pack_node_id.clone(),
            pack_content_digest.clone(),
            component_path,
            component_digest.clone(),
            interface_version,
            execution_profile_digest.clone(),
        ),
    }
    .map_err(|error| invalid_projected_record(plan_id, error))?;
    let resources = transform
        .resources()
        .iter()
        .map(|resource| PrepareTransformResourceV1::new(resource.name(), resource.digest().clone()))
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| invalid_projected_record(plan_id, error))?;
    let diagnostics = transform
        .diagnostics()
        .iter()
        .map(transform_diagnostic_view)
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| invalid_projected_record(plan_id, error))?;
    PrepareTransformProvenanceV1::new(
        transform.name(),
        implementation,
        transform.request_digest().clone(),
        transform.document_digest().clone(),
        resources,
        transform.response_digest().clone(),
        diagnostics,
    )
    .map_err(|error| invalid_projected_record(plan_id, error))
}

fn store_transform_diagnostic(
    diagnostic: &PrepareTransformDiagnosticV1,
) -> Result<TransformDiagnosticV1, malm_store::PreparedRecordError> {
    let severity = match diagnostic.severity() {
        PrepareTransformDiagnosticSeverityV1::Error => {
            return Err(malm_store::PreparedRecordError::InvalidField {
                field: "transform diagnostic severity",
                reason: "successful transforms cannot contain error diagnostics",
            });
        }
        PrepareTransformDiagnosticSeverityV1::Warning => TransformDiagnosticSeverityV1::Warning,
        PrepareTransformDiagnosticSeverityV1::Info => TransformDiagnosticSeverityV1::Info,
    };
    let primary = diagnostic.primary().map(|location| match location {
        PrepareTransformDiagnosticLocationV1::Source(source) => {
            TransformDiagnosticLocationV1::Source {
                authority_label: source.authority_label().clone(),
                authority_identity: source.authority_identity().clone(),
                document_path: source.document_path().to_owned(),
                source_byte_len: source.source_byte_len(),
                start: source.start(),
                end: source.end(),
            }
        }
        PrepareTransformDiagnosticLocationV1::Output(output) => {
            TransformDiagnosticLocationV1::Output {
                start: output.start(),
                end: output.end(),
            }
        }
    });
    TransformDiagnosticV1::new(
        severity,
        diagnostic.code(),
        diagnostic.message(),
        primary,
        diagnostic.notes().to_vec(),
    )
}

fn transform_diagnostic_view(
    diagnostic: &TransformDiagnosticV1,
) -> Result<PrepareTransformDiagnosticV1, malm_types::DeploymentDtoError> {
    let severity = match diagnostic.severity() {
        TransformDiagnosticSeverityV1::Error => PrepareTransformDiagnosticSeverityV1::Error,
        TransformDiagnosticSeverityV1::Warning => PrepareTransformDiagnosticSeverityV1::Warning,
        TransformDiagnosticSeverityV1::Info => PrepareTransformDiagnosticSeverityV1::Info,
    };
    let primary = match diagnostic.primary() {
        Some(TransformDiagnosticLocationV1::Source {
            authority_label,
            authority_identity,
            document_path,
            source_byte_len,
            start,
            end,
        }) => Some(PrepareTransformDiagnosticLocationV1::Source(
            PrepareTransformSourceLocationV1::new(
                authority_label.clone(),
                authority_identity.clone(),
                document_path,
                *source_byte_len,
                *start,
                *end,
            )?,
        )),
        Some(TransformDiagnosticLocationV1::Output { start, end }) => {
            Some(PrepareTransformDiagnosticLocationV1::Output(
                PrepareTransformOutputLocationV1::new(*start, *end)?,
            ))
        }
        None => None,
    };
    PrepareTransformDiagnosticV1::new(
        severity,
        diagnostic.code(),
        diagnostic.message(),
        primary,
        diagnostic.notes().to_vec(),
    )
}

fn invalid_projected_record(plan_id: &PreparedId, detail: impl std::fmt::Display) -> EngineError {
    prepared_error(
        Path::new(plan_id.as_str()),
        PreparedStoreIssue::InvalidRecord {
            detail: detail.to_string(),
        },
    )
}

pub(super) fn operation_view(
    operation: &PreparedOperationV1,
) -> Result<PrepareOperationV1, EngineError> {
    let observation = operation.observation();
    match operation {
        PreparedOperationV1::EnsureDirectory { mode, .. } => {
            if matches!(observation.leaf(), LeafObservationV1::Present(_)) {
                PrepareOperationV1::replace_directory(
                    observation.authority().clone(),
                    observation.relative_path(),
                    *mode,
                )
            } else {
                PrepareOperationV1::ensure_directory(
                    observation.authority().clone(),
                    observation.relative_path(),
                    *mode,
                )
            }
        }
        PreparedOperationV1::PlaceFile {
            artifact_id,
            mode,
            replace_existing,
            ..
        } => {
            if *replace_existing {
                PrepareOperationV1::replace_file(
                    observation.authority().clone(),
                    observation.relative_path(),
                    artifact_id.clone(),
                    *mode,
                )
            } else {
                PrepareOperationV1::place_file(
                    observation.authority().clone(),
                    observation.relative_path(),
                    artifact_id.clone(),
                    *mode,
                )
            }
        }
        PreparedOperationV1::PlaceSymlink {
            object,
            replace_existing,
            ..
        } => {
            if *replace_existing {
                PrepareOperationV1::replace_symlink(
                    observation.authority().clone(),
                    observation.relative_path(),
                    object.clone(),
                )
            } else {
                PrepareOperationV1::place_symlink(
                    observation.authority().clone(),
                    observation.relative_path(),
                    object.clone(),
                )
            }
        }
        PreparedOperationV1::PlaceTree {
            tree,
            archive_provenance,
            replace_existing,
            ..
        } => match (*replace_existing, archive_provenance.as_ref()) {
            (true, Some(provenance)) => PrepareOperationV1::replace_archive_tree(
                observation.authority().clone(),
                observation.relative_path(),
                tree.clone(),
                archive_provenance_view(provenance),
            ),
            (true, None) => PrepareOperationV1::replace_tree(
                observation.authority().clone(),
                observation.relative_path(),
                tree.clone(),
            ),
            (false, Some(provenance)) => PrepareOperationV1::place_archive_tree(
                observation.authority().clone(),
                observation.relative_path(),
                tree.clone(),
                archive_provenance_view(provenance),
            ),
            (false, None) => PrepareOperationV1::place_tree(
                observation.authority().clone(),
                observation.relative_path(),
                tree.clone(),
            ),
        },
        PreparedOperationV1::RemoveLeaf { .. } => PrepareOperationV1::remove_leaf(
            observation.authority().clone(),
            observation.relative_path(),
        ),
        PreparedOperationV1::AssertAbsent { .. } => PrepareOperationV1::assert_absent(
            observation.authority().clone(),
            observation.relative_path(),
        ),
        PreparedOperationV1::AssertExact { state, .. } => PrepareOperationV1::assert_exact(
            observation.authority().clone(),
            observation.relative_path(),
            target_state_view_for_projection(state),
        ),
    }
    .map_err(|error| invalid_record_from_path(operation.observation(), error.to_string()))
}

fn target_state_view_for_projection(state: &StateTargetStateV1) -> PrepareTargetStateV1 {
    match state {
        StateTargetStateV1::File { file: Some(file) } => {
            PrepareTargetStateV1::file(file.digest().clone(), file.byte_len(), file.mode())
                .expect("validated file state projects into the semantic DTO")
        }
        StateTargetStateV1::Directory {
            directory: Some(directory),
        } => PrepareTargetStateV1::directory(directory.mode())
            .expect("validated directory state projects into the semantic DTO"),
        StateTargetStateV1::Symlink {
            symlink: Some(symlink),
        } => PrepareTargetStateV1::symlink(symlink.object().clone()),
        StateTargetStateV1::Tree { tree: Some(tree) } => match tree.archive_provenance() {
            Some(provenance) => PrepareTargetStateV1::archive_tree(
                tree.tree().clone(),
                archive_provenance_view(provenance),
            ),
            None => PrepareTargetStateV1::tree(tree.tree().clone()),
        },
        StateTargetStateV1::File { file: None }
        | StateTargetStateV1::Directory { directory: None }
        | StateTargetStateV1::Symlink { symlink: None }
        | StateTargetStateV1::Tree { tree: None } => {
            unreachable!("validated exact assertions contain present state")
        }
    }
}

