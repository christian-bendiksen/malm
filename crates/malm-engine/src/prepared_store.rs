fn find_artifact<'a>(
    engine: &Engine,
    record: &'a PreparedRecordV1,
    artifact_id: &ArtifactId,
) -> Result<&'a PreparedArtifactV1, EngineError> {
    record
        .artifacts()
        .binary_search_by(|artifact| artifact.id().cmp(artifact_id))
        .ok()
        .map(|index| &record.artifacts()[index])
        .ok_or_else(|| {
            prepared_error(
                engine.config.state_root(),
                PreparedStoreIssue::UnknownArtifact(artifact_id.clone()),
            )
        })
}

fn prepared_item_count(record: &PreparedRecordV1) -> usize {
    record
        .inputs()
        .len()
        .saturating_add(record.transforms().len())
        .saturating_add(record.artifacts().len())
        .saturating_add(record.findings().len())
        .saturating_add(record.operations().len())
        .saturating_add(record.desired_snapshot().targets().len())
        .saturating_add(record.retention_authority().restore_points().len())
        .saturating_add(record.retention_authority().explicit_pins().len())
}

