pub(super) fn load_retained_graph_record(
    engine: &Engine,
    initial: &StateGenerationV1,
) -> Result<Option<PreparedRecordV1>, EngineError> {
    let mut generation = initial.clone();
    let mut visited = BTreeSet::new();
    for _ in 0..65_536 {
        if !visited.insert(generation.plan_id().clone()) {
            return Err(invalid_record(
                engine,
                "retained graph lineage contains a cycle".to_owned(),
            ));
        }
        let record = load_record(engine, generation.plan_id())?;
        let locks = record
            .inputs()
            .iter()
            .filter(|input| input.kind() == PreparedInputKindV1::Lock)
            .collect::<Vec<_>>();
        let sources = record
            .inputs()
            .iter()
            .filter(|input| input.kind() == PreparedInputKindV1::Source)
            .collect::<Vec<_>>();
        let has_pack_source = sources
            .iter()
            .any(|input| input.name().starts_with("pack:"));
        if !locks.is_empty() || has_pack_source {
            let [lock] = locks.as_slice() else {
                return Err(invalid_record(
                    engine,
                    "retained graph authority must contain exactly one lock input".to_owned(),
                ));
            };
            if lock.name() != "locked-graph" || lock.digest() != record.graph_digest() {
                return Err(invalid_record(
                    engine,
                    "retained graph lock input differs from the prepared graph identity".to_owned(),
                ));
            }
            if sources.is_empty()
                || sources
                    .iter()
                    .any(|input| !input.name().starts_with("pack:"))
            {
                return Err(invalid_record(
                    engine,
                    "retained graph authority must contain only named pack source inputs"
                        .to_owned(),
                ));
            }
            return Ok(Some(record));
        }

        let source = match generation.transition() {
            PreparedTransitionV1::Reconcile | PreparedTransitionV1::NamespaceRemoval { .. } => {
                return Ok(None);
            }
            PreparedTransitionV1::Disable => generation
                .restore_point()
                .map(|point| point.generation().clone()),
            PreparedTransitionV1::Enable { restore_point } => {
                Some(restore_point.generation().clone())
            }
            PreparedTransitionV1::Checkout { source_generation } => Some(source_generation.clone()),
            PreparedTransitionV1::RetentionAuthority => generation.previous_generation().cloned(),
        }
        .ok_or_else(|| {
            invalid_record(
                engine,
                "lifecycle generation does not retain a graph-authority source".to_owned(),
            )
        })?;
        let Ok(source_generation) = engine
            .committer_v1()
            .and_then(|committer| committer.inspect_generation_v1(&source))
        else {
            // A legacy lifecycle generation may outlive the weak predecessor
            // edge from which an optional pack authority would be recovered.
            return Ok(None);
        };
        generation = source_generation;
        if generation.namespace() != initial.namespace() {
            return Err(invalid_record(
                engine,
                "retained graph lineage crosses namespace authority".to_owned(),
            ));
        }
    }
    Err(invalid_record(
        engine,
        "retained graph lineage exceeds the validation limit".to_owned(),
    ))
}

