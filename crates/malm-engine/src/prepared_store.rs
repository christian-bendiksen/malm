pub(super) fn commit_error(engine: &Engine, error: CommitError) -> EngineError {
    let reason = match error {
        CommitError::StaleNamespaceHead {
            namespace,
            expected,
            actual,
        } => PreparedStoreIssue::StaleNamespaceHead {
            namespace,
            expected,
            actual,
        },
        CommitError::TargetOwnershipConflict {
            requesting_namespace,
            owning_namespace,
            requesting_authority,
            owning_authority,
            requested_path,
            owned_path,
            overlap,
        } => PreparedStoreIssue::TargetOwnershipConflict {
            requesting_namespace: Box::new(requesting_namespace),
            owning_namespace: Box::new(owning_namespace),
            requesting_authority,
            owning_authority,
            requested_path,
            owned_path,
            overlap,
        },
        CommitError::UnownedTargetMutation {
            namespace,
            authority,
            relative_path,
        } => PreparedStoreIssue::UnownedTargetMutation {
            namespace,
            authority,
            relative_path,
        },
        error => return EngineError::Commit { source: error },
    };
    prepared_error(engine.config.state_root(), reason)
}

