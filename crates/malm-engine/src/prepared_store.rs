/// Enumerates every durable prepared-plan record with its file modification
/// time.
///
/// The modification time is a host filesystem observation for human review
/// ordering only; it never participates in any digest, canonical encoding,
/// or machine-facing contract. Records whose names are not valid plan
/// identifiers are reported as errors rather than skipped.
pub(super) fn list_plans(engine: &Engine) -> Result<Vec<crate::PlanIndexEntryV1>, EngineError> {
    let ready = engine.open_ready_store()?;
    ready.revalidate()?;
    let Some(directories) = PreparedDirectories::open(&ready, false)? else {
        return Ok(Vec::new());
    };
    let mut plans = Vec::new();
    let mut entries = Dir::read_from(&directories.prepared).map_err(|source| {
        errno_error(
            "enumerate prepared plans",
            &directories.prepared_path,
            source,
        )
    })?;
    while let Some(entry) = entries.read() {
        let entry = entry.map_err(|source| {
            errno_error(
                "enumerate prepared plans",
                &directories.prepared_path,
                source,
            )
        })?;
        let name_bytes = entry.file_name().to_bytes();
        if matches!(name_bytes, b"." | b"..") {
            continue;
        }
        let name = std::str::from_utf8(name_bytes)
            .map_err(|_| invalid_record(engine, "prepared record name is not UTF-8".to_owned()))?;
        let plan_id =
            PreparedId::new(name.to_owned()).map_err(|error| invalid_record(engine, error))?;
        let stat = statat(
            &directories.prepared,
            entry.file_name(),
            AtFlags::SYMLINK_NOFOLLOW,
        )
        .map_err(|source| {
            errno_error(
                "inspect prepared plan record",
                &directories.prepared_path.join(name),
                source,
            )
        })?;
        if FileType::from_raw_mode(stat.st_mode) != FileType::RegularFile {
            return Err(invalid_record(
                engine,
                format!("prepared record {name} is not a regular file"),
            ));
        }
        plans.push(crate::PlanIndexEntryV1::new(
            plan_id,
            stat.st_mtime,
            i64::try_from(stat.st_mtime_nsec).unwrap_or(0),
        ));
    }
    plans.sort_by(|left, right| {
        (
            right.modified_seconds(),
            right.modified_nanoseconds(),
            left.plan_id().as_str(),
        )
            .cmp(&(
                left.modified_seconds(),
                left.modified_nanoseconds(),
                right.plan_id().as_str(),
            ))
    });
    Ok(plans)
}

pub(super) fn inspect_plan(
    engine: &Engine,
    request: &PreparedPlanInspectionRequestV1,
) -> Result<PreparedDeploymentV1, EngineError> {
    let (record, _) =
        load_record_with_limit(engine, request.plan_id(), request.max_decoded_bytes())?;
    if prepared_item_count(&record) > request.max_items() {
        return Err(prepared_error(
            engine.config.state_root(),
            PreparedStoreIssue::InvalidRecord {
                detail: "prepared plan exceeds the requested inspection item limit".to_owned(),
            },
        ));
    }
    project(request.plan_id(), &record)
}

